import { createRequire } from "node:module";
import postcss from "postcss";
import { describe, expect, it } from "vitest";

const require = createRequire(import.meta.url);
const fontScale = require("../../scripts/build/postcss-interface-font-scale.cjs");

async function transform(css: string, from = "/project/src/app.css") {
  return (await postcss([fontScale()]).process(css, { from })).css;
}

describe("interface font scale PostCSS plugin", () => {
  it("scales explicit font sizes, including calculations, but leaves other properties and inherited sizes alone", async () => {
    const css = await transform(`
      .a { font-size: 13px; width: 13px; }
      .b { font-size: 0.875rem; }
      .c { font-size: clamp(12px, 2vw, 20px); }
      .d { font-size: calc(12px * var(--zoom, 1)); }
      .e { font-size: inherit; }
    `);
    expect(css).toContain(
      "font-size: calc(13px * var(--interface-font-scale, 1))",
    );
    expect(css).toContain("width: 13px");
    expect(css).toContain("calc(0.875rem * var(--interface-font-scale, 1))");
    expect(css).toContain(
      "calc(clamp(12px, 2vw, 20px) * var(--interface-font-scale, 1))",
    );
    expect(css).toContain(
      "calc(calc(12px * var(--zoom, 1)) * var(--interface-font-scale, 1))",
    );
    expect(css).toContain("font-size: inherit");
  });

  it("leaves root sizes, dependencies, and document preview styles unchanged", async () => {
    const css =
      "html { font-size: 16px } :root { font-size: 16px } .a { font-size: 14px }";
    expect(await transform(css)).toContain("html { font-size: 16px }");
    expect(await transform(css)).toContain(":root { font-size: 16px }");
    expect(
      await transform(css, "/project/node_modules/package/style.css"),
    ).toBe(css);
    expect(
      await transform(
        css,
        "/project/src/features/agent/agent-document-viewer.css",
      ),
    ).toBe(css);
    expect(
      await transform(
        css,
        "C:\\project\\src\\features\\agent\\agent-spreadsheet-view.css",
      ),
    ).toBe(css);
  });

  it("scales utility classes generated by Tailwind in the same processing pass", async () => {
    const tailwind = require("tailwindcss");
    const result = await postcss([
      tailwind({ content: [{ raw: '<div class="text-sm"></div>' }] }),
      fontScale(),
    ]).process("@tailwind utilities;", { from: "/project/src/index.css" });
    expect(result.css).toContain(
      "calc(0.875rem * var(--interface-font-scale, 1))",
    );
  });
});
